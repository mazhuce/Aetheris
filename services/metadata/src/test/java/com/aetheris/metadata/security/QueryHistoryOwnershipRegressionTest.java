package com.aetheris.metadata.security;

import com.aetheris.metadata.controller.AdhocQueryController;
import com.aetheris.metadata.controller.QueryHistoryController;
import com.aetheris.metadata.entity.DataSource;
import com.aetheris.metadata.mapper.QueryHistoryMapper;
import com.aetheris.metadata.service.*;
import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.apache.ibatis.session.SqlSession;
import org.junit.jupiter.api.*;
import org.springframework.http.MediaType;
import org.springframework.http.converter.json.MappingJackson2HttpMessageConverter;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;

import java.sql.Connection;
import java.util.*;
import java.util.concurrent.atomic.AtomicLong;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;

/** Actual MyBatis predicates on H2 + Ed25519/MVC. The live-session fixture is not an auth deployment. */
class QueryHistoryOwnershipRegressionTest {
    private static final String PRIVATE_SQL = "SELECT 'private-sql-canary' AS value";
    private static final String DRIVER_SECRET = "password=driver-secret-canary; jdbc:postgresql://private-host/db";
    private final MetadataProofFixture proof = new MetadataProofFixture();
    private final ObjectMapper json = new ObjectMapper().findAndRegisterModules();
    private final AtomicLong liveUid = new AtomicLong(42), liveAv = new AtomicLong(3);
    private final JdbcService queries = mock(JdbcService.class);
    private Connection keeper;
    private SqlSession session;
    private JdbcTemplate jdbc;
    private MockMvc mvc;

    @BeforeEach void setup() throws Exception {
        var database = new DriverManagerDataSource("jdbc:h2:mem:history_" + UUID.randomUUID().toString().replace("-", "")
                + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE", "sa", "");
        keeper = database.getConnection(); jdbc = new JdbcTemplate(database);
        jdbc.execute("CREATE SCHEMA metadata");
        // Future nullable columns are fixture-only here; current application ignores them before the repair.
        jdbc.execute("""
            CREATE TABLE metadata.adhoc_query_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(64) NOT NULL, datasource_id BIGINT NOT NULL, datasource_name VARCHAR(255),
                sql_text TEXT NOT NULL, status VARCHAR(16) NOT NULL, row_count BIGINT, duration_ms BIGINT,
                error_message TEXT, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                owner_uid BIGINT, request_id VARCHAR(128), error_code VARCHAR(64))
            """);
        var configuration = new MybatisConfiguration(); configuration.setMapUnderscoreToCamelCase(true);
        configuration.addMapper(QueryHistoryMapper.class);
        var factory = new MybatisSqlSessionFactoryBean(); factory.setDataSource(database); factory.setConfiguration(configuration); factory.afterPropertiesSet();
        session = Objects.requireNonNull(factory.getObject()).openSession(true);
        var history = new QueryHistoryService(session.getMapper(QueryHistoryMapper.class));
        var permissions = mock(AuthPermissionClient.class);
        when(permissions.check(anyString(), anyString(), nullable(Long.class), anyString(), anyMap()))
                .thenReturn(new AuthPermissionClient.Access(true, "fixture", true));
        var security = new MetadataSecurity(permissions);
        var sources = mock(DataSourceService.class); var source = new DataSource();
        source.setId(7L); source.setName("Business source"); source.setStatus("active");
        when(sources.getById(7L)).thenReturn(source);
        when(queries.query(eq(source), anyString())).thenAnswer(call -> new LinkedHashMap<>(Map.of("rows", List.of(), "rowCount", 0)));
        mvc = MockMvcBuilders.standaloneSetup(new AdhocQueryController(sources, queries, history, security),
                        new QueryHistoryController(history, security))
                .setMessageConverters(new MappingJackson2HttpMessageConverter(json))
                .setControllerAdvice(new MetadataAccessExceptionHandler())
                .addFilters(proof.direct((uid, name, av) -> uid == liveUid.get() && "alice".equals(name) && av == liveAv.get()))
                .build();
    }

    @AfterEach void cleanup() throws Exception {
        if (session != null) session.close();
        if (keeper != null) keeper.close();
    }

    @Test void newUidCannotReadSqlOwnedByDeletedSameNameAccount() throws Exception {
        query(42, 3, 200); liveUid.set(43);
        var response = mvc.perform(get("/api/metadata/query-history").header("X-Aetheris-User-Proof", token(43, 3))).andReturn().getResponse();
        assertEquals(200, response.getStatus());
        assertEquals(0, json.readTree(response.getContentAsString()).size());
        assertFalse(response.getContentAsString().contains("private-sql-canary"));
    }

    @Test void newUidCannotDeleteOldSameNameHistoryById() throws Exception {
        query(42, 3, 200); long id = onlyId(); liveUid.set(43);
        var response = mvc.perform(delete("/api/metadata/query-history/" + id).header("X-Aetheris-User-Proof", token(43, 3))).andReturn().getResponse();
        assertAll(() -> assertEquals(404, response.getStatus()), () -> assertEquals(1, count()));
    }

    @Test void newUidCannotClearOldSameNameHistory() throws Exception {
        query(42, 3, 200); liveUid.set(43);
        var response = mvc.perform(delete("/api/metadata/query-history").header("X-Aetheris-User-Proof", token(43, 3))).andReturn().getResponse();
        assertEquals(200, response.getStatus());
        assertAll(() -> assertEquals(0, json.readTree(response.getContentAsString()).path("deleted").asInt()), () -> assertEquals(1, count()));
    }

    @Test void legacyNullUidIsNotGuessedFromUsername() throws Exception {
        jdbc.update("INSERT INTO metadata.adhoc_query_history(username,datasource_id,sql_text,status) VALUES ('alice',7,?,'success')", PRIVATE_SQL);
        var response = mvc.perform(get("/api/metadata/query-history").header("X-Aetheris-User-Proof", token(42, 3))).andReturn().getResponse();
        assertEquals(200, response.getStatus()); assertEquals(0, json.readTree(response.getContentAsString()).size());
        assertEquals(1, count());
    }

    @Test void newWriteStoresStableUidAndVerifiedRequestId() throws Exception {
        query(42, 3, 200);
        assertEquals(42L, jdbc.queryForObject("SELECT owner_uid FROM metadata.adhoc_query_history", Long.class));
        assertEquals("metadata-v2-test", jdbc.queryForObject("SELECT request_id FROM metadata.adhoc_query_history", String.class));
    }

    @Test void sameUidAfterAccessVersionChangeCanStillCopyOwnSql() throws Exception {
        query(42, 3, 200); liveAv.set(4);
        var response = mvc.perform(get("/api/metadata/query-history").header("X-Aetheris-User-Proof", token(42, 4))).andReturn().getResponse();
        assertEquals(200, response.getStatus()); var rows = json.readTree(response.getContentAsString());
        assertEquals(1, rows.size()); assertEquals(PRIVATE_SQL, rows.get(0).path("sqlText").asText());
        assertEquals(403, mvc.perform(get("/api/metadata/query-history").header("X-Aetheris-User-Proof", token(42, 3))).andReturn().getResponse().getStatus());
    }

    @Test void jdbcFailureDoesNotExposeOrPersistDriverSecrets() throws Exception {
        when(queries.query(any(), anyString())).thenThrow(new IllegalStateException(DRIVER_SECRET));
        var response = query(42, 3, 502);
        assertFalse(response.getContentAsString().contains("driver-secret-canary"));
        assertFalse(Objects.requireNonNull(jdbc.queryForObject("SELECT error_message FROM metadata.adhoc_query_history", String.class)).contains("driver-secret-canary"));
    }

    @Test void legacyDriverErrorIsHiddenWhileOwnSqlRemainsReusable() throws Exception {
        jdbc.update("INSERT INTO metadata.adhoc_query_history(username,datasource_id,sql_text,status,owner_uid,error_message) VALUES ('alice',7,?,'failed',42,?)", PRIVATE_SQL, DRIVER_SECRET);
        var response = mvc.perform(get("/api/metadata/query-history").header("X-Aetheris-User-Proof", token(42, 3))).andReturn().getResponse();
        assertEquals(200, response.getStatus());
        assertTrue(response.getContentAsString().contains("private-sql-canary"));
        assertFalse(response.getContentAsString().contains("driver-secret-canary"));
    }

    @Test void forgedOwnerAndUsernameParametersCannotExpandPersonalScope() throws Exception {
        query(42, 3, 200); liveUid.set(43);
        var response=mvc.perform(get("/api/metadata/query-history?ownerUid=42&username=alice")
                .header("X-Aetheris-User-Proof",token(43,3)).header("X-User-Name","alice").header("X-User-Id","42"))
                .andReturn().getResponse();
        assertEquals(200,response.getStatus());assertEquals(0,json.readTree(response.getContentAsString()).size());
        assertEquals(1,count());
    }

    @Test void policyExceptionsDoNotEchoConfigurationSecrets() throws Exception {
        when(queries.query(any(),anyString())).thenThrow(new IllegalArgumentException(DRIVER_SECRET));
        var response=query(42,3,400);
        assertFalse(response.getContentAsString().contains("driver-secret-canary"));
        assertEquals("SQL_POLICY_REJECTED",json.readTree(response.getContentAsString()).path("code").asText());
        assertEquals("metadata-v2-test",json.readTree(response.getContentAsString()).path("requestId").asText());
    }

    private org.springframework.mock.web.MockHttpServletResponse query(long uid, long av, int status) throws Exception {
        var response = mvc.perform(post("/api/metadata/query").header("X-Aetheris-User-Proof", token(uid, av))
                .contentType(MediaType.APPLICATION_JSON).content(json.writeValueAsBytes(Map.of("datasourceId", 7, "sql", PRIVATE_SQL))))
                .andReturn().getResponse();
        assertEquals(status, response.getStatus()); return response;
    }
    private String token(long uid, long av) { return proof.user("metadata", uid, "alice", av); }
    private long onlyId() { return Objects.requireNonNull(jdbc.queryForObject("SELECT id FROM metadata.adhoc_query_history", Long.class)); }
    private int count() { return Objects.requireNonNull(jdbc.queryForObject("SELECT count(*) FROM metadata.adhoc_query_history", Integer.class)); }
}
